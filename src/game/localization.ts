export function translateDynamicName(engName: string, lang: string): string {
  if (lang === "EN") return engName;
  const words = engName.split(/[- ]/);
  const translated = words.map(word => {
    const cleanWord = word.toLowerCase().trim();
    if (!cleanWord) return "";
    
    if (lang === "ID") {
      const idEntry = INDONESIAN_WORD_MAP[cleanWord];
      if (idEntry) return idEntry;
    }
    
    const entry = WORD_MAP[cleanWord];
    if (entry && entry[lang]) {
      return entry[lang];
    }
    return word;
  });

  if (lang === "JA" || lang === "ZH" || lang === "KO") {
    return translated.join("");
  }
  return translated.join(" ");
}

export function t(key: string, replacement?: Record<string, string | number>, defaultVal?: string): string {
  const dictionary = TRANSLATIONS[currentLanguage] || TRANSLATIONS.EN;
  
  // 1. Resolve missing custom HUD or additional keys
  let text: string | undefined = undefined;
  if (ADDITIONAL_TRANSLATIONS[currentLanguage] && ADDITIONAL_TRANSLATIONS[currentLanguage][key] !== undefined) {
    text = ADDITIONAL_TRANSLATIONS[currentLanguage][key];
  } else if (ADDITIONAL_TRANSLATIONS.EN && ADDITIONAL_TRANSLATIONS.EN[key] !== undefined) {
    text = ADDITIONAL_TRANSLATIONS.EN[key];
  } else if (EXTRA_HUD_TRANSLATIONS[currentLanguage] && EXTRA_HUD_TRANSLATIONS[currentLanguage][key] !== undefined) {
    text = EXTRA_HUD_TRANSLATIONS[currentLanguage][key];
  } else if (EXTRA_HUD_TRANSLATIONS.EN[key] !== undefined) {
    text = EXTRA_HUD_TRANSLATIONS.EN[key];
  }

  // 2. Resolve upgrade names and descriptions
  if (!text) {
    if (key.startsWith("up_name_")) {
      const upId = key.substring(8);
      const matchedName = translateDynamicName(upId.replace(/_/g, " "), currentLanguage);
      if (matchedName && matchedName !== upId.replace(/_/g, " ")) {
        text = matchedName;
      }
    } else if (key.startsWith("up_desc_")) {
      const upId = key.substring(8);
      // Give a clean dynamic localized description template for stats/weapons
      if (currentLanguage === "ES") {
        text = `Calibra o incrementa las funciones de ${translateDynamicName(upId.replace(/_/g, " "), "ES")} para mayor rendimiento orbital.`;
      } else if (currentLanguage === "FR") {
        text = `Met en œuvre ou améliore les performances de ${translateDynamicName(upId.replace(/_/g, " "), "FR")} pour un meilleur rendement.`;
      } else if (currentLanguage === "DE") {
        text = `Überträgt oder kalibriert ${translateDynamicName(upId.replace(/_/g, " "), "DE")} für maximale Leistung und Präzision.`;
      } else if (currentLanguage === "JA") {
        text = `${translateDynamicName(upId.replace(/_/g, " "), "JA")}の出力とパラメーターを調整し、軌道制御力を高めます。`;
      } else if (currentLanguage === "ZH") {
        text = `调优并增强 ${translateDynamicName(upId.replace(/_/g, " "), "ZH")} 的底层运行效能与范围。`;
      } else if (currentLanguage === "KO") {
        text = `${translateDynamicName(upId.replace(/_/g, " "), "KO")} 장비를 활성화하고 선체 조작력을 극대화합니다.`;
      } else if (currentLanguage === "PT") {
        text = `Ajusta as especificações de de ${translateDynamicName(upId.replace(/_/g, " "), "PT")} para eficiência quântica.`;
      } else if (currentLanguage === "RU") {
        text = `Модернизация и настройка узла ${translateDynamicName(upId.replace(/_/g, " "), "RU")} для повышения перегрузки.`;
      } else if (currentLanguage === "IT") {
        text = `Configura o aumenta le prestazioni di ${translateDynamicName(upId.replace(/_/g, " "), "IT")} per una migliore efficienza orbitale.`;
      }
    } else if (key.startsWith("wp_")) {
      const wpType = key.substring(3).toLowerCase();
      const matchId = MAP_WP_TYPE_TO_ID[wpType] || wpType;
      text = translateDynamicName(matchId.replace(/_/g, " "), currentLanguage);
    } else if (key.endsWith("_name")) {
      const baseId = key.substring(0, key.length - 5);
      text = translateDynamicName(baseId.replace(/_/g, " "), currentLanguage);
    } else if (key.endsWith("_description")) {
      if (defaultVal && defaultVal !== key) {
        text = defaultVal;
      } else {
        const baseId = key.substring(0, key.length - 12);
        if (currentLanguage === "ES") {
          text = `Usa para propulsarse, orientarse o redireccionar los cristales del casco con ${translateDynamicName(baseId.replace(/_/g, " "), "ES")}.`;
        } else if (currentLanguage === "FR") {
          text = `Activez la fonction ${translateDynamicName(baseId.replace(/_/g, " "), "FR")} pour naviguer de manière optimale.`;
        } else if (currentLanguage === "JA") {
          text = `${translateDynamicName(baseId.replace(/_/g, " "), "JA")}を使用して、アリーナ内を高速移動・テザー旋回します。`;
        } else if (currentLanguage === "IT") {
          text = `Usa per muoverti, orientarti o reindirizzare i cristalli del veicolo con ${translateDynamicName(baseId.replace(/_/g, " "), "IT")}.`;
        } else {
          text = `Enables active ${translateDynamicName(baseId.replace(/_/g, " "), "EN")} to interact with physics parameters inside the field.`;
        }
      }
    }
  }

  // 3. Fallback to standard translations
  if (!text) {
    text = dictionary[key] || TRANSLATIONS.EN[key] || defaultVal || key;
  }
  
  if (replacement) {
    Object.entries(replacement).forEach(([k, val]) => {
      text = text!.replace(`{${k}}`, String(val));
    });
  }
  
  return text!;
}

export function useLanguage() {
  const [lang, setLang] = useState<LanguageCode>(currentLanguage);

  useEffect(() => {
    const handleLanguageChange = () => {
      setLang(currentLanguage);
    };
    window.addEventListener('game_language_changed', handleLanguageChange);
    return () => {
      window.removeEventListener('game_language_changed', handleLanguageChange);
    };
  }, []);

  return {
    lang,
    setLang: (newLang: LanguageCode) => {
      setLanguage(newLang);
    },
    t: (key: string, replacement?: Record<string, string | number>, defaultVal?: string) => {
      return t(key, replacement, defaultVal);
    }
  };
}
